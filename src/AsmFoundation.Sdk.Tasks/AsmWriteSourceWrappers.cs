using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;
using System.Text.RegularExpressions;
using Microsoft.Build.Framework;
using Microsoft.Build.Utilities;

namespace AsmFoundation.Sdk.Tasks;

/// <summary>
/// Writes, for each GNU-syntax source that needs one, the file llvm-mc assembles in its place:
/// what must come before the source's first line (the defines of a WebAssembly build, the
/// platform layer of ImplicitUsings), then the source's own text behind a line marker that
/// keeps every diagnostic and every DWARF line on the source itself.
/// </summary>
/// <remarks>
/// <para>
/// Why a wrapper at all: llvm-mc has no pre-include option (NASM's <c>-P</c>), so ImplicitUsings
/// cannot put the platform layer in front of a source any other way; and a WebAssembly source
/// cannot receive the SDK's defines on the command line, because llvm-mc turns each
/// <c>--defsym</c> into a constant symbol and its wasm object writer stops on any constant
/// symbol ("NAME: absolute addressing not supported!", measured with LLVM 23.1.5). In a wasm
/// wrapper each define is a label of size 0 in a data section of its own, which <c>.ifdef</c>
/// sees exactly as it sees a defsym, and which the object can hold (a local data symbol; the
/// empty segment is dropped by wasm-ld's garbage collection).
/// </para>
/// <para>
/// Why the source's text is copied rather than included: llvm-mc's <c>-g</c> names the MAIN
/// file in every DWARF line row, with line numbers from whatever buffer the instruction came
/// from, and gives the last statement of an included file the including file's line (measured
/// with llvm-dwarfdump, LLVM 23.1.5, on wasm32, AArch64 and x86-64). A wrapper that included the
/// source therefore pointed debuggers at obj/.../implicit/x.s with wrong lines. The copy sits
/// behind a C preprocessor line marker, <c># 1 "C:/repo/src/x.s"</c>, which llvm-mc honors as
/// clang's integrated assembler does for preprocessed <c>.S</c> files: every row then names the
/// source and its own line, and an error in the source is reported at its full path, line and
/// column, as the wrapper's former <c>.include</c> of the full path had it reported (MSBuild then
/// shows it as an error at that place, which IDEs open). The full path costs no
/// reproducibility: llvm-mc writes the marker's name into DWARF only, which Release objects do
/// not have (measured: no trace of the name in a Release object of wasm32 or AArch64, two in a
/// Debug one).
/// </para>
/// <para>
/// Footguns: a source's own <c>.include</c> of a file with INSTRUCTIONS in it still gets llvm-mc's
/// main-file attribution for those lines (llvm-mc's limitation, the same without a wrapper);
/// includes of macros and constants are unaffected. A UTF-8 byte order mark at the start of a
/// source is dropped from the copy (behind the marker it would be three stray bytes in the middle
/// of a line). Each wrapper is rewritten only when its text changes, so its time stamp does not
/// make the object look stale; the object's own inputs (the source, include files, options)
/// decide whether llvm-mc runs.
/// </para>
/// <para>Errors: ASM0018 (a define that cannot become a WebAssembly label: it has a value, or
/// it is not a symbol name), ASM0026 (a source cannot be read or its wrapper written).</para>
/// </remarks>
public sealed class AsmWriteSourceWrappers : Task
{
    /// <summary>
    /// The text that starts every file this task writes. Comments use <c>//</c>, which llvm-mc
    /// accepts for every target (a <c>#</c> at the start of a line could be read as a line marker).
    /// </summary>
    private const string Header = "// Generated by AsmFoundation.Sdk: llvm-mc assembles this file in place of the source named by the line marker below. Do not edit; edit the source.";

    /// <summary>
    /// A symbol name llvm-mc accepts as a label without quotes: a letter, underscore, dot or
    /// dollar, then those and digits. A define outside it would stop llvm-mc in the wrapper, far
    /// from the project file where the define was written, so it is refused here.
    /// </summary>
    private static readonly Regex LabelName = new("^[A-Za-z_.$][A-Za-z0-9_.$]*$", RegexOptions.CultureInvariant);

    /// <summary>
    /// The sources to wrap. Metadata: <c>SourceWrapper</c>, the file to write (relative to the
    /// project folder or absolute), and <c>SourceToolPath</c>, the name the line marker gives the
    /// source (its full path, forward slashes; the item's FullPath when missing). Items without
    /// <c>SourceWrapper</c> are skipped: they are assembled as they are.
    /// </summary>
    [Required]
    public ITaskItem[] Sources { get; set; } = Array.Empty<ITaskItem>();

    /// <summary>
    /// The defines to declare as labels, for a WebAssembly build (empty otherwise: other targets
    /// get them as llvm-mc's defsym arguments). Each must be a bare name: a <c>NAME=VALUE</c>
    /// entry is ASM0018, because a label has an address, not a value.
    /// </summary>
    public string[] DefineLabels { get; set; } = Array.Empty<string>();

    /// <summary>
    /// The include file that ImplicitUsings puts in front of every source (asmsdk-gnu-implicit.inc,
    /// found through llvm-mc's include path), or empty when ImplicitUsings is off.
    /// </summary>
    public string ImplicitInclude { get; set; } = "";

    /// <summary>The project folder: relative <c>SourceWrapper</c> paths are taken from it.</summary>
    [Required]
    public string ProjectDirectory { get; set; } = "";

    /// <summary>Every wrapper this build uses (written now or unchanged), for FileWrites.</summary>
    [Output]
    public ITaskItem[] Wrappers { get; set; } = Array.Empty<ITaskItem>();

    /// <summary>Writes the wrappers whose text changed.</summary>
    /// <returns>True when every wrapper is in place; false after logging ASM0018 or ASM0026.</returns>
    public override bool Execute()
    {
        // The defines first, once: one bad entry would otherwise be reported per source.
        string[] labels = DefineLabels.Where(d => d.Length != 0).Distinct(StringComparer.Ordinal).ToArray();
        foreach (string define in labels)
        {
            // IndexOf, not Contains(char): the task targets netstandard2.0, which lacks the overload.
            if (define.IndexOf('=') >= 0)
            {
                Log.LogError(null, "ASM0018", null, null, 0, 0, 0, 0,
                    "The define '{0}' has a value, and a WebAssembly source cannot receive one: llvm-mc's wasm objects hold no constant symbols, so the SDK passes each define as a label, which .ifdef tests but which has no value. Define the name alone (.ifdef works), or write the value in the source.",
                    define);
                return false;
            }

            if (!LabelName.IsMatch(define))
            {
                Log.LogError(null, "ASM0018", null, null, 0, 0, 0, 0,
                    "The define '{0}' is not a symbol name, so it cannot become the label through which a WebAssembly source sees it. Use letters, digits, '_', '.' and '$', not starting with a digit.",
                    define);
                return false;
            }
        }

        string prelude = Prelude(labels, ImplicitInclude);
        var wrappers = new List<ITaskItem>();
        foreach (ITaskItem source in Sources)
        {
            string wrapper = source.GetMetadata("SourceWrapper");
            if (wrapper.Length == 0)
            {
                continue;
            }

            string wrapperPath = Path.GetFullPath(Path.Combine(ProjectDirectory, wrapper));
            string markerName = source.GetMetadata("SourceToolPath");
            if (markerName.Length == 0)
            {
                markerName = source.GetMetadata("FullPath").Replace('\\', '/');
            }

            try
            {
                byte[] text = Compose(prelude, markerName, File.ReadAllBytes(source.GetMetadata("FullPath")));
                WriteIfChanged(wrapperPath, text);
            }
            catch (Exception ex) when (ex is IOException or UnauthorizedAccessException or ArgumentException or NotSupportedException)
            {
                // A source listed but missing, or an obj/ folder that cannot be written: say which
                // file, rather than letting llvm-mc fail later on a wrapper that does not exist.
                Log.LogError(null, "ASM0026", null, source.ItemSpec, 0, 0, 0, 0,
                    "Cannot prepare {0} for llvm-mc (its generated copy {1}): {2}", source.ItemSpec, wrapperPath, ex.Message);
                return false;
            }

            wrappers.Add(new TaskItem(wrapperPath));
        }

        Wrappers = wrappers.ToArray();
        return true;
    }

    /// <summary>
    /// The lines every wrapper of this build shares, before its marker: the header, the define
    /// labels of a WebAssembly build, and the ImplicitUsings include.
    /// </summary>
    /// <param name="labels">The define names, already checked; empty for a build that passes defines with defsym.</param>
    /// <param name="implicitInclude">The ImplicitUsings include file's name, or empty.</param>
    /// <returns>The text, each line ending in "\n".</returns>
    /// <remarks>
    /// The labels' section is entered with <c>.section</c> and left with an explicit
    /// <c>.section .text,"",@</c>: llvm-mc's wasm parser treats a bare <c>.text</c> as a no-op
    /// ("FIXME: .text currently no-op", LLVM's WasmAsmParser), so after a bare <c>.text</c> the
    /// source's first function would land in the data section, and the object writer stop with
    /// "section already has a defining function" (measured). <c>.pushsection</c> is not
    /// available either: the wasm parser has no such directive. All labels sit at offset 0 of an
    /// empty section, with size 0, which <c>.size</c> must state: llvm-mc's wasm writer stops on
    /// a data symbol without a size ("data symbols must have a size set with .size").
    /// </remarks>
    private static string Prelude(IReadOnlyList<string> labels, string implicitInclude)
    {
        var text = new StringBuilder();
        text.Append(Header).Append('\n');
        if (labels.Count != 0)
        {
            text.Append("// The SDK's defines, as labels: .ifdef sees them as it sees a defsym (see AsmWriteSourceWrappers).\n");
            text.Append(".section .data.asmsdk_defines,\"\",@\n");
            foreach (string label in labels)
            {
                text.Append(label).Append(":\n");
            }

            foreach (string label in labels)
            {
                text.Append(".size ").Append(label).Append(", 0\n");
            }

            text.Append(".section .text,\"\",@\n");
        }

        if (implicitInclude.Length != 0)
        {
            text.Append(".include \"").Append(implicitInclude).Append("\"\n");
        }

        return text.ToString();
    }

    /// <summary>
    /// A wrapper's bytes: the prelude, the line marker that makes the next line line 1 of the
    /// source, then the source's bytes as they are (encoding and line endings untouched), less a
    /// leading UTF-8 byte order mark, which behind the marker would be three stray bytes.
    /// </summary>
    /// <param name="prelude">The shared lines (<see cref="Prelude"/>).</param>
    /// <param name="markerName">The source's name in the marker: its full path, forward slashes.</param>
    /// <param name="source">The source file's bytes.</param>
    /// <returns>The wrapper's bytes.</returns>
    /// <remarks>
    /// A source that does not end with a newline gets one: its last statement then ends inside
    /// this buffer, never at the end of the file, where llvm-mc took the line of whatever came
    /// next (the include case above). Quotes and backslashes in the marker's name are escaped
    /// as in a C string, which is how llvm-mc reads it.
    /// </remarks>
    private static byte[] Compose(string prelude, string markerName, byte[] source)
    {
        int start = source.Length >= 3 && source[0] == 0xEF && source[1] == 0xBB && source[2] == 0xBF ? 3 : 0;
        string marker = "# 1 \"" + markerName.Replace("\\", "\\\\").Replace("\"", "\\\"") + "\"\n";
        byte[] head = Encoding.UTF8.GetBytes(prelude + marker);
        bool endsWithNewline = source.Length > start && source[source.Length - 1] == (byte)'\n';
        using var output = new MemoryStream(head.Length + source.Length + 1);
        output.Write(head, 0, head.Length);
        output.Write(source, start, source.Length - start);
        if (!endsWithNewline)
        {
            output.WriteByte((byte)'\n');
        }

        return output.ToArray();
    }

    /// <summary>Writes a file unless it already holds exactly these bytes.</summary>
    /// <param name="path">The wrapper's full path; its folder is created when missing.</param>
    /// <param name="bytes">The wrapper's content.</param>
    /// <exception cref="IOException">The file or its folder cannot be written.</exception>
    /// <exception cref="UnauthorizedAccessException">The file or its folder is not writable.</exception>
    private static void WriteIfChanged(string path, byte[] bytes)
    {
        // Enumerable.SequenceEqual: netstandard2.0 has no span comparison without System.Memory,
        // and wrappers are source-sized, so the byte-by-byte loop costs nothing measurable.
        if (File.Exists(path) && File.ReadAllBytes(path).SequenceEqual(bytes))
        {
            return;
        }

        Directory.CreateDirectory(Path.GetDirectoryName(path)!);
        File.WriteAllBytes(path, bytes);
    }
}
