using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;

namespace AsmFoundation.Sdk.Tasks;

/// <summary>
/// Writes the C# source of the generated fallback loader: a module initializer that adds an
/// AssemblyLoadContext.ResolvingUnmanagedDll handler, which loads an asm library from where
/// BinariesCopyPath put it when .NET's own probing found nothing.
/// </summary>
/// <remarks>
/// <para>
/// Why a fallback, and why this event: the .NET host finds the libraries through deps.json
/// (see AsmAddNativeAssetsToDepsFile), but NativeAOT reads no deps.json, and an app can get the
/// files without an entry (through a class library whose asm reference does not flow to it,
/// PrivateAssets="all"). ResolvingUnmanagedDll runs only after the runtime's own probing failed,
/// any number of handlers may be attached, and a handler that returns zero passes the request
/// on, so a resolver of the user's own (NativeLibrary.SetDllImportResolver, which runs first)
/// keeps precedence and two generated loaders never conflict. Measured on win-x64 (framework-
/// dependent, self-contained, both single-file kinds, NativeAOT) and linux-x64 (the first four):
/// a library only in native/ loaded through the handler in every case.
/// </para>
/// <para>
/// The source needs .NET 5 or later (ModuleInitializerAttribute, OperatingSystem) and C# 9.
/// It is plain, fully qualified code: no using directives, so a project's global usings,
/// nullable setting or analyzers never change its meaning, and the auto-generated header keeps
/// analyzers off it.
/// </para>
/// </remarks>
internal static class NativeLoaderSource
{
    /// <summary>The namespace of every generated loader class.</summary>
    internal const string Namespace = "AsmFoundation.Sdk.Generated";

    /// <summary>Writes the loader's source.</summary>
    /// <param name="className">The class name (unique in its assembly: one per project, one per package).</param>
    /// <param name="libraries">
    /// Each library: its name in [DllImport]/[LibraryImport] (the asm project's AssemblyName,
    /// which the file names derive from: calc.dll, libcalc.so, libcalc.dylib), and the folder of
    /// its files relative to the app ("" = the app folder; {rid} = the RID each file was built for).
    /// The text of a folder is inserted as is, so a caller may pass an MSBuild property reference
    /// in its place (the package targets do).
    /// </param>
    /// <param name="origin">Who wrote it, for the header ("AsmFoundation.Sdk 0.3.0 for Calc.App").</param>
    /// <returns>The C# source, with "\n" line ends.</returns>
    /// <exception cref="ArgumentException">A library name or folder contains a quote or a backslash (it could not sit in a C# string literal).</exception>
    internal static string Generate(string className, IEnumerable<KeyValuePair<string, string>> libraries, string origin)
    {
        var source = new StringBuilder();
        source.Append("// <auto-generated>\n");
        source.Append("//   Written by ").Append(origin).Append(".\n");
        source.Append("//   Loads the native libraries of asm references from where BinariesCopyPath put them, when\n");
        source.Append("//   .NET's own probing found nothing (NativeAOT reads no deps.json). It runs after that\n");
        source.Append("//   probing and after any resolver of your own; set AsmGenerateNativeLibraryLoader=false\n");
        source.Append("//   to go without it.\n");
        source.Append("// </auto-generated>\n");
        source.Append("#nullable enable\n");
        source.Append("#pragma warning disable CA2255 // [ModuleInitializer] in a library: it only adds a fallback resolver.\n\n");
        source.Append("namespace ").Append(Namespace).Append("\n{\n");
        source.Append("    /// <summary>Loads this assembly's asm libraries from their BinariesCopyPath folders when nothing else did.</summary>\n");
        source.Append("    internal static class ").Append(className).Append("\n    {\n");
        source.Append("        /// <summary>Each library: its name, and the folder of its files relative to the app ({rid}: the RID each was built for).</summary>\n");
        source.Append("        private static readonly string[][] Libraries =\n        {\n");
        foreach (KeyValuePair<string, string> library in libraries.OrderBy(l => l.Key, StringComparer.Ordinal))
        {
            source.Append("            new[] { ").Append(Literal(library.Key)).Append(", ").Append(Literal(library.Value)).Append(" },\n");
        }

        source.Append("        };\n\n");
        source.Append(Body);
        source.Append("    }\n}\n");
        return source.ToString();
    }

    /// <summary>A C# string literal of a library name or folder.</summary>
    /// <param name="text">The text.</param>
    /// <returns>The text in double quotes.</returns>
    /// <exception cref="ArgumentException">The text holds a quote or a backslash.</exception>
    private static string Literal(string text)
    {
        // BinariesCopyPath rejects quotes and turns backslashes into slashes, and an asm
        // project's AssemblyName is a file name: neither can hold them. Refusing them here keeps
        // that true if a caller ever passes something else.
        if (text.IndexOf('"') >= 0 || text.IndexOf('\\') >= 0)
        {
            throw new ArgumentException($"'{text}' cannot be written into the generated loader.", nameof(text));
        }

        return "\"" + text + "\"";
    }

    /// <summary>The members after the table: registration, resolution, file names, RIDs, folders.</summary>
    private const string Body =
        "        /// <summary>1 once the handler is attached (a module initializer runs once, but a guard costs nothing).</summary>\n" +
        "        private static int registered;\n\n" +
        "        /// <summary>Attaches the handler when the assembly is first used, before any of its P/Invokes run.</summary>\n" +
        "        [global::System.Runtime.CompilerServices.ModuleInitializer]\n" +
        "        internal static void Register()\n" +
        "        {\n" +
        "            if (global::System.Threading.Interlocked.Exchange(ref registered, 1) == 0)\n" +
        "            {\n" +
        "                global::System.Runtime.Loader.AssemblyLoadContext.Default.ResolvingUnmanagedDll += Resolve;\n" +
        "            }\n" +
        "        }\n\n" +
        "        /// <summary>Loads a library this table knows, from its folder; zero passes the request on.</summary>\n" +
        "        private static global::System.IntPtr Resolve(global::System.Reflection.Assembly assembly, string libraryName)\n" +
        "        {\n" +
        "            foreach (string[] library in Libraries)\n" +
        "            {\n" +
        "                if (!Matches(library[0], libraryName))\n" +
        "                {\n" +
        "                    continue;\n" +
        "                }\n\n" +
        "                string file = FileName(library[0]);\n" +
        "                bool perRid = library[1].Contains(\"{rid}\");\n" +
        "                foreach (string directory in Directories())\n" +
        "                {\n" +
        "                    foreach (string rid in perRid ? Rids() : new[] { \"\" })\n" +
        "                    {\n" +
        "                        string path = global::System.IO.Path.Combine(directory, library[1].Replace(\"{rid}\", rid), file);\n" +
        "                        if (global::System.IO.File.Exists(path) && global::System.Runtime.InteropServices.NativeLibrary.TryLoad(path, out global::System.IntPtr handle))\n" +
        "                        {\n" +
        "                            return handle;\n" +
        "                        }\n" +
        "                    }\n" +
        "                }\n" +
        "            }\n\n" +
        "            return global::System.IntPtr.Zero;\n" +
        "        }\n\n" +
        "        /// <summary>Whether a requested name means this library: \"calc\", \"calc.dll\", \"libcalc\" or \"libcalc.so\" all name calc.</summary>\n" +
        "        private static bool Matches(string name, string requested)\n" +
        "        {\n" +
        "            global::System.StringComparison comparison = global::System.OperatingSystem.IsWindows() ? global::System.StringComparison.OrdinalIgnoreCase : global::System.StringComparison.Ordinal;\n" +
        "            foreach (string extension in new[] { \".dll\", \".so\", \".dylib\" })\n" +
        "            {\n" +
        "                if (requested.EndsWith(extension, global::System.StringComparison.OrdinalIgnoreCase))\n" +
        "                {\n" +
        "                    requested = requested.Substring(0, requested.Length - extension.Length);\n" +
        "                    break;\n" +
        "                }\n" +
        "            }\n\n" +
        "            return string.Equals(requested, name, comparison)\n" +
        "                || (requested.StartsWith(\"lib\", global::System.StringComparison.Ordinal) && string.Equals(requested.Substring(3), name, comparison));\n" +
        "        }\n\n" +
        "        /// <summary>The library's file on this OS, as AsmSdk names it.</summary>\n" +
        "        private static string FileName(string name) =>\n" +
        "            global::System.OperatingSystem.IsWindows() ? name + \".dll\"\n" +
        "            : global::System.OperatingSystem.IsMacOS() ? \"lib\" + name + \".dylib\"\n" +
        "            : \"lib\" + name + \".so\";\n\n" +
        "        /// <summary>The RIDs whose builds run here, nearest first: a musl machine also takes the glibc-free linux build.</summary>\n" +
        "        private static string[] Rids()\n" +
        "        {\n" +
        "            string? arch = global::System.Runtime.InteropServices.RuntimeInformation.ProcessArchitecture switch\n" +
        "            {\n" +
        "                global::System.Runtime.InteropServices.Architecture.X64 => \"x64\",\n" +
        "                global::System.Runtime.InteropServices.Architecture.Arm64 => \"arm64\",\n" +
        "                _ => null,\n" +
        "            };\n" +
        "            if (arch is null)\n" +
        "            {\n" +
        "                return global::System.Array.Empty<string>();\n" +
        "            }\n\n" +
        "            if (global::System.OperatingSystem.IsWindows())\n" +
        "            {\n" +
        "                return new[] { \"win-\" + arch };\n" +
        "            }\n\n" +
        "            if (global::System.OperatingSystem.IsMacOS())\n" +
        "            {\n" +
        "                return new[] { \"osx-\" + arch };\n" +
        "            }\n\n" +
        "            // Distribution builds of .NET report their own RID (alpine.3.20-x64): musl shows in either spelling.\n" +
        "            string runtime = global::System.Runtime.InteropServices.RuntimeInformation.RuntimeIdentifier;\n" +
        "            return runtime.Contains(\"musl\") || runtime.Contains(\"alpine\")\n" +
        "                ? new[] { \"linux-musl-\" + arch, \"linux-\" + arch }\n" +
        "                : new[] { \"linux-\" + arch };\n" +
        "        }\n\n" +
        "        /// <summary>The app's folder, then the host's native search folders (a self-extracting single file unpacks there).</summary>\n" +
        "        private static global::System.Collections.Generic.IEnumerable<string> Directories()\n" +
        "        {\n" +
        "            yield return global::System.AppContext.BaseDirectory;\n" +
        "            if (global::System.AppContext.GetData(\"NATIVE_DLL_SEARCH_DIRECTORIES\") is string list)\n" +
        "            {\n" +
        "                foreach (string directory in list.Split(global::System.IO.Path.PathSeparator))\n" +
        "                {\n" +
        "                    if (directory.Length != 0)\n" +
        "                    {\n" +
        "                        yield return directory;\n" +
        "                    }\n" +
        "                }\n" +
        "            }\n" +
        "        }\n";
}
